<?php

namespace App\Filament\SystemAdmin\Resources\Users;

use App\Filament\SystemAdmin\Resources\Users\Pages\CreateUser;
use App\Filament\SystemAdmin\Resources\Users\Pages\EditUser;
use App\Filament\SystemAdmin\Resources\Users\Pages\ListUsers;
use App\Filament\SystemAdmin\Resources\Users\Pages\ViewUser;
use App\Filament\SystemAdmin\Resources\Users\Schemas\UserForm;
use App\Filament\SystemAdmin\Resources\Users\Schemas\UserInfolist;
use App\Filament\SystemAdmin\Resources\Users\Tables\UsersTable;
use App\Models\User;
use BackedEnum;
use Filament\Resources\Resource;
use Filament\Schemas\Schema;
use Filament\Tables\Table;

class UserResource extends Resource
{
    protected static ?string $model = User::class;

    protected static string|BackedEnum|null $navigationIcon = 'heroicon-o-users';

    protected static ?string $navigationLabel = 'المستخدمون';

    protected static ?string $modelLabel = 'مستخدم';

    protected static ?string $pluralModelLabel = 'المستخدمون';

    protected static ?int $navigationSort = 1;

    public static function form(Schema $schema): Schema
    {
        return UserForm::configure($schema);
    }

    public static function table(Table $table): Table
    {
        return UsersTable::configure($table);
    }

    public static function infolist(Schema $schema): Schema
    {
        return UserInfolist::configure($schema);
    }

    public static function getRelations(): array
    {
        return [];
    }

    public static function getPages(): array
    {
        return [
            'index'  => ListUsers::route('/'),
            'create' => CreateUser::route('/create'),
            'view'   => ViewUser::route('/{record}'),
            'edit'   => EditUser::route('/{record}/edit'),
        ];
    }
}
